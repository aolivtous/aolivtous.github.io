#!/usr/bin/env python3
"""Copy a validated slice export into the portfolio and prepare viewer data."""
import argparse
from copy import deepcopy
import json
from pathlib import Path
import shutil

from PIL import Image
from matplotlib import colormaps
import numpy as np


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--case", action="append", required=True,
                        help="Explicitly choose which case to package; repeat to select more")
    parser.add_argument("--prediction-only-case", action="append", default=[],
                        help="For a selected case, copy only prediction and uncertainty; repeat as needed")
    parser.add_argument("--destination", type=Path,
                        default=Path(__file__).resolve().parents[1] / "figs/mumins/viewer")
    args = parser.parse_args()
    if args.destination.exists():
        parser.error("Choose a new destination; existing assets are not overwritten")
    manifest = json.loads((args.source / "manifest.json").read_text())
    cases = []
    required = {"baseline", "followup", "prediction_0", "uncertainty_0", "error_0"}
    selected = [entry for entry in manifest["cases"] if entry["id"] in args.case]
    if set(args.case) != {entry["id"] for entry in selected}:
        parser.error("Requested case not found in the export")
    if not set(args.prediction_only_case).issubset(args.case):
        parser.error("Prediction-only cases must also be selected with --case")
    copies = []
    for entry in selected:
        metadata = json.loads((args.source / entry["metadata"]).read_text())
        prediction_only = entry["id"] in args.prediction_only_case
        names = {"prediction_0", "uncertainty_0"} if prediction_only else required
        if not names.issubset(metadata["series"]):
            parser.error(f"{entry['id']}: required series missing")
        if not prediction_only and not metadata["comparison_complete"]:
            parser.error(f"{entry['id']}: complete comparison required for the webpage")
        folder = args.source / entry["id"]
        for plane, info in metadata["planes"].items():
            for name in names:
                for index in range(info["frames"]):
                    path = folder / plane / name / f"{index:03d}.png"
                    if not path.is_file():
                        parser.error(f"Missing frame: {path}")
        metadata = deepcopy(metadata)
        metadata["series"] = {name: path for name, path in metadata["series"].items() if name in names}
        if prediction_only:
            metadata["id"] = entry["id"] + "_predicted"
            metadata["display"].pop("error", None)
            for key in ("original_scan_headers", "error_validation", "preprocessing", "missing_series"):
                metadata.pop(key, None)
            metadata["comparison_complete"] = False
            metadata["view"] = "prediction_and_uncertainty_only"
        cases.append(metadata)
        copies.append((folder, metadata))
    args.destination.mkdir(parents=True)
    # Copy only allowed series, never a whole case directory containing hidden references.
    for folder, metadata in copies:
        destination = args.destination / metadata["id"]
        destination.mkdir()
        for plane in metadata["planes"]:
            for name in metadata["series"]:
                shutil.copytree(folder / plane / name, destination / plane / name)
        (destination / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    selected_manifest = {
        "schema_version": manifest["schema_version"],
        "cases": [{"id": c["id"], "modality": c["modality"],
                   "metadata": c["id"] + "/metadata.json",
                   "comparison_complete": c["comparison_complete"],
                   "series": list(c["series"]),
                   "png_frames": sum(p["frames"] for p in c["planes"].values()) * len(c["series"])}
                  for c in cases],
        "display": {c["modality"]: c["display"] for c in cases},
    }
    (args.destination / "manifest.json").write_text(json.dumps(selected_manifest, indent=2) + "\n")
    for name in {scale["colormap"] for c in cases for scale in c["display"].values() if "colormap" in scale}:
        palette = colormaps[name](np.linspace(0, 1, 256), bytes=True)[None, :, :3]
        Image.fromarray(palette).save(args.destination / f"{name}.png")
    data = {"cases": cases}
    (args.destination / "viewer-data.js").write_text(
        "// Generated by scripts/prepare_mumins_web_assets.py from a validated export.\n"
        "window.MUMINS_VIEWER_DATA = " + json.dumps(data, ensure_ascii=False, allow_nan=False) + ";\n"
    )
    print(f"Prepared {len(cases)} selected cases in {args.destination}")


if __name__ == "__main__":
    main()
